create table if not exists public.episodes (
  id bigint generated by default as identity primary key,
  air_date date not null unique,
  season integer,
  show_number integer,
  source_url text not null,
  imported_at timestamptz not null default now()
);

create table if not exists public.clues (
  id bigint generated by default as identity primary key,
  episode_id bigint not null references public.episodes(id) on delete cascade,
  round text not null check (round in ('J', 'DJ', 'FJ')),
  category text not null,
  value integer,
  board_position integer,
  clue text not null,
  response text not null,
  is_daily_double boolean not null default false,
  unique (episode_id, round, category, board_position)
);

create index if not exists clues_episode_idx on public.clues(episode_id);
create index if not exists clues_lookup_idx on public.clues(episode_id, round, category, value);

alter table public.episodes enable row level security;
alter table public.clues enable row level security;

